import path from "node:path";
import {
  PROJECT_PATHS,
  writeJson,
  writeText,
} from "./lib/project-index.mjs";
import {
  VARIANT_FAMILIES,
  buildVariantMatrix,
  loadVariantPolicy,
  validateVariantMatrix,
  validateVariantPolicy,
} from "./lib/variant-matrix.mjs";

const policy = await loadVariantPolicy();
const { rows } = await buildVariantMatrix(policy);
const policyIssues = [
  ...(policy ? validateVariantPolicy(policy, rows.map((row) => row.base)) : ["Variant policy has not been initialized."]),
  ...validateVariantMatrix(rows),
];
const families = Object.keys(VARIANT_FAMILIES);

const summary = {
  baseBlocks: rows.length,
  currentDefinitions: rows.reduce(
    (total, row) => total + families.reduce((subtotal, family) => subtotal + row.variants[family].current.definitionCount, 0),
    0,
  ),
  duplicateDefinitions: rows.reduce(
    (total, row) => total + families.reduce((subtotal, family) => subtotal + Math.max(0, row.variants[family].current.definitionCount - 1), 0),
    0,
  ),
  vanillaSlabOverlaps: rows.filter((row) => row.variants.slab.vanilla.length > 0).length,
  vanillaStairsOverlaps: rows.filter((row) => row.variants.stairs.vanilla.length > 0).length,
  pendingDecisions: rows.reduce(
    (total, row) => total + families.filter((family) => row.variants[family].decision === "pending").length,
    0,
  ),
  unresolvedSources: rows.filter((row) => !row.sourceExists).length,
  policyIssues: policyIssues.length,
};

const report = {
  schemaVersion: 1,
  decisionValues: ["pending", "generate", "skip", "use_vanilla"],
  summary,
  policyIssues,
  rows,
};

function csvCell(value) {
  const text = String(value ?? "");
  return /[",\n]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

const csvHeader = [
  "base",
  "source",
  ...families.flatMap((family) => [
    `${family}_decision`,
    `${family}_atelier_definitions`,
    `${family}_vanilla_ids`,
  ]),
  "notes",
];
const csvRows = rows.map((row) => [
  row.base,
  row.source,
  ...families.flatMap((family) => [
    row.variants[family].decision,
    row.variants[family].current.definitionCount,
    row.variants[family].vanilla.join(";"),
  ]),
  row.notes,
]);
const csv = [csvHeader, ...csvRows].map((row) => row.map(csvCell).join(",")).join("\n");

function compactCurrent(variant) {
  if (!variant.current.present) return "—";
  return variant.current.definitionCount > 1 ? `yes (${variant.current.definitionCount} defs)` : "yes";
}

function compactVanilla(variant) {
  return variant.vanilla.length > 0 ? variant.vanilla.join("<br>") : "—";
}

function compactReview(variant) {
  const current = variant.current.present ? `${variant.current.definitionCount} def(s)` : "absent";
  const vanilla = variant.vanilla.length > 0 ? `vanilla: ${variant.vanilla.join(", ")}` : "no vanilla match";
  return `${variant.decision}<br>${current}<br>${vanilla}`;
}

const overlaps = rows.filter(
  (row) => row.variants.slab.vanilla.length > 0 || row.variants.stairs.vanilla.length > 0,
);
const markdown = [
  "# Variant review",
  "",
  "Generated by `npm run variants:audit`. Edit decisions in `content/variant-policy.json`, never in this report.",
  "",
  "Decision values: `pending`, `generate`, `skip`, `use_vanilla`.",
  "",
  "## Summary",
  "",
  "| Metric | Value |",
  "| --- | ---: |",
  ...Object.entries(summary).map(([key, value]) => `| ${key} | ${value} |`),
  "",
  "## Possible vanilla overlaps",
  "",
  "| Base | Source | Atelier slab | Vanilla slab | Atelier stairs | Vanilla stairs |",
  "| --- | --- | --- | --- | --- | --- |",
  ...overlaps.map((row) => `| ${row.base} | ${row.source ?? "unresolved"} | ${compactCurrent(row.variants.slab)} | ${compactVanilla(row.variants.slab)} | ${compactCurrent(row.variants.stairs)} | ${compactVanilla(row.variants.stairs)} |`),
  "",
  "## Complete inventory and decision matrix",
  "",
  "| Base | Source | Slab | Stairs | Vertical slab | Wall |",
  "| --- | --- | --- | --- | --- | --- |",
  ...rows.map((row) => `| ${row.base} | ${row.source ?? "unresolved"} | ${compactReview(row.variants.slab)} | ${compactReview(row.variants.stairs)} | ${compactReview(row.variants.vertical_slab)} | ${compactReview(row.variants.wall)} |`),
];

await writeJson(path.join(PROJECT_PATHS.generated, "variant-review.json"), report);
await writeText(path.join(PROJECT_PATHS.generated, "variant-review.csv"), csv);
await writeText(path.join(PROJECT_PATHS.generated, "variant-review.md"), markdown.join("\n"));

console.log(`Variant bases: ${summary.baseBlocks}`);
console.log(`Possible vanilla overlaps: ${summary.vanillaSlabOverlaps} slabs / ${summary.vanillaStairsOverlaps} stairs`);
console.log(`Pending decisions: ${summary.pendingDecisions}`);
console.log("Reports: tools/generated/variant-review.{json,csv,md}");
